import { mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect, it } from "vitest";
import { createNextIntegrationFixture } from "../fixtures/next-integration.js";
import { DockerRepairSession } from "../../src/runner/repair-session.js";
import { planFixTasks } from "../../src/planner/planner.js";
import { applyCodemod } from "../../src/fixers/codemods/index.js";
import { applyInlineContrastFix } from "../../src/fixers/contrast-patch.js";
import { observationsToState } from "../../src/scanner/observations.js";
import { verifyPerPatch } from "../../src/verifier/per-patch.js";

it("runs actual Next.js production gates and bisects a dev-valid but build-breaking source fix", async () => {
  const tempRoot = process.env.ACCESSWRIGHT_TMP_ROOT ?? join(tmpdir(), "accesswright-integration");
  await mkdir(tempRoot, { recursive: true });
  const fixture = await mkdtemp(join(tempRoot, "next-fixture-"));
  await createNextIntegrationFixture(fixture);
  const original = await readFile(join(fixture, "components/Controls.tsx"), "utf8");
  const session = await DockerRepairSession.prepare({ repoPath: fixture, tempRoot, runtimeRoot: process.cwd(), privateDiagnostics: true, config: { scan: { mobile: true, darkScheme: false }, offline: true } });
  try {
    expect(session.baselineChecks.map(check => check.status), JSON.stringify(session.baselineChecks)).toEqual(["passed", "passed", "passed", "passed"]);
    expect(session.routes).toEqual(["/", "/help"]);
    expect(session.inspection.processEnvironmentNames).not.toContain("OPENAI_API_KEY");
    expect(session.inspection.processEnvironmentNames).not.toContain("ACCESSWRIGHT_FIXTURE_PRIVATE_VALUE");
    const application = session.applicationContainer;
    let before = session.observations;
    const task = planFixTasks(observationsToState(before).violations).find(task => task.ruleId === "aria-valid-attr");
    if (!task?.source) throw new Error("The real invalid-ARIA target must be source-mapped");
    const patch = applyCodemod(await session.readSource(task.source.file), task);
    if (!patch) throw new Error("Expected a real codemod patch");
    const changedSource = patch.changes[0];
    if (!changedSource) throw new Error("The codemod did not contain a source change");
    changedSource.after += '\nexport const productionTypeError: number = "must fail the real compiler";\n';
    const normalized = await session.applyPatch(patch);
    const after = await session.scan(task.routes, "bad-candidate");
    const accepted = verifyPerPatch({ task, before: observationsToState(before.filter(page => task.routes.includes(page.route))), after: observationsToState(after) });
    expect(accepted.accepted).toBe(true);
    await session.record(normalized, task, accepted);
    session.updateObservations(after);
    before = session.observations;
    const contrast = planFixTasks(observationsToState(before).violations).find(task => task.ruleId === "color-contrast");
    if (!contrast?.source) throw new Error("The real contrast target must be mapped");
    const contrastPatch = applyInlineContrastFix(await session.readSource(contrast.source.file), contrast);
    if (!contrastPatch) throw new Error("Expected an actual contrast optimization");
    const normalizedContrast = await session.applyPatch(contrastPatch);
    const contrastAfter = await session.scan(contrast.routes, "contrast-candidate");
    const contrastAccepted = verifyPerPatch({ task: contrast, before: observationsToState(before.filter(page => contrast.routes.includes(page.route))), after: observationsToState(contrastAfter) });
    expect(contrastAccepted.accepted).toBe(true);
    await session.record(normalizedContrast, contrast, contrastAccepted);
    expect(session.applicationContainer).toBe(application);
    const final = await session.verifyFinal();
    expect(final.failures).toEqual([]);
    expect(final.droppedFixIds).toContain(task.id);
    expect(final.acceptedFixIds).toContain(contrast.id);
    expect(final.acceptedFixIds).not.toContain(task.id);
    expect(session.finalChecks.map(check => check.status), JSON.stringify(session.finalChecks)).toEqual(["passed", "passed", "passed", "passed"]);
    expect(await readFile(join(fixture, "components/Controls.tsx"), "utf8")).toBe(original);
    await writeFile(join(session.evidenceDir, "integration-report.json"), JSON.stringify({ kind: "real-next-production-bisect", provider: "none", baseline: session.baselineChecks, final: session.finalChecks, result: final, routes: session.routes, sourceMapping: task.source, persistentApplicationContainer: application }, null, 2));
    console.log(`Next.js integration evidence: ${session.evidenceDir}`);
  } finally { await session.close(); }
});
